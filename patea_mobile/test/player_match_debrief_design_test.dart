import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:patea_mobile/core/models/player_activity_models.dart';
import 'package:patea_mobile/core/services/player_profile_service.dart';
import 'package:patea_mobile/core/theme/app_theme.dart';
import 'package:patea_mobile/core/widgets/patea_card.dart';
import 'package:patea_mobile/features/players/widgets/player_match_debrief.dart';
import 'goldens/arnes.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  GoogleFonts.config.allowRuntimeFetching = false;
  setUp(() { GoogleFonts.config.allowRuntimeFetching = false; SharedPreferences.setMockInitialValues({}); });
  Future<void> mount(WidgetTester tester, List<MatchFeedback> games, {String playerId = 'own', bool compact = true, ThemeData? theme, double scale = 1}) async {
    final errors = await montarPantalla(tester, ProviderScope(overrides: [
      playerActivityProvider(playerId).overrideWith((ref) async => games),
    ], child: Scaffold(body: SingleChildScrollView(child: Padding(padding: const EdgeInsets.all(18),
      child: PlayerMatchDebrief(playerId: playerId, compact: compact))))),
      tema: theme ?? AppTheme.darkTheme, escala: scale, tamano: const Size(960, 2400));
    expect(errors, isEmpty);
    expect(tester.takeException(), isNull);
  }
  for (final theme in [AppTheme.darkTheme, AppTheme.lightTheme]) {
    for (final id in ['own', 'other']) {
      testWidgets('Open feedback in $id profile fits 320px at 1.3x ${theme.brightness}', (tester) async {
        await mount(tester, [feedbackDePerfil], playerId: id, theme: theme, scale: 1.3);
        expect(find.byType(PateaCard), findsNothing);
        expect(find.text('Evolución en este partido'), findsOneWidget);
        expect(find.text('OVR 55 → 56'), findsOneWidget);
        expect(find.text('Pase'), findsOneWidget);
        expect(find.text('Defensa'), findsOneWidget);
        expect(find.text('-4'), findsOneWidget);
        expect(find.text('Compañero anónimo'), findsNWidgets(2));
        expect(find.text('El Terror del Área'), findsNWidgets(2));
        expect(tester.takeException(), isNull);
      });
    }
  }
  testWidgets('Anonymous identities stay hidden; automatic and text feedback stay readable', (tester) async {
    await mount(tester, [const MatchFeedback(matchId: 'privacy', title: 'Otro partido', peerEvaluations: [
      PeerEvaluation(id: 'hidden', evaluatorId: 'secret-id', evaluatorDisplayName: 'Nombre privado', evaluatorPhotoUrl: 'https://invalid.test/private.png', isAnonymous: true,
        textDescription: 'Buena lectura de juego.'),
      PeerEvaluation(id: 'auto', evaluatorId: 'system', autoGenerated: true, rating: 6.5, aiSummary: 'Resumen del partido.'),
      PeerEvaluation(id: 'public', evaluatorId: 'visible', evaluatorDisplayName: 'Compañero con identidad revelada', rating: 8),
    ])], scale: 1.3);
    expect(find.text('Nombre privado'), findsNothing);
    expect(find.text('Compañero anónimo'), findsOneWidget);
    expect(find.text('Evaluación automática'), findsOneWidget);
    expect(find.text('Buena lectura de juego.'), findsOneWidget);
    expect(find.text('Resumen del partido.'), findsOneWidget);
    expect(find.text('Compañero con identidad revelada'), findsOneWidget);
    expect(tester.takeException(), isNull);
  });
  testWidgets('Full history preserves every match; compact shows only the latest', (tester) async {
    const second = MatchFeedback(matchId: 'second', title: 'Partido anterior');
    await mount(tester, [feedbackDePerfil, second]);
    expect(find.text('Partido anterior'), findsNothing);
    expect(find.text('Ver historial completo'), findsOneWidget);
    await tester.pumpWidget(const SizedBox.shrink());
    await mount(tester, [feedbackDePerfil, second], compact: false);
    expect(find.text('Partido anterior'), findsOneWidget);
    expect(find.text('Ver historial completo'), findsNothing);
  });
}
