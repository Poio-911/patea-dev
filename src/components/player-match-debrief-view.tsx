// ─── Main Component ───────────────────────────────────────────────────────────

export function PlayerMatchDebriefView({ playerId, compact }: PlayerMatchDebriefViewProps) {
  const firestore = useFirestore();
  const { user } = useUser();
  const { toast } = useToast();
  const [activities, setActivities] = useState<MatchFeedbackContext[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  const isOwner = user?.uid === playerId;

  const handleRequestIdentity = async (evaluationId: string) => {
    try {
      const result = await requestIdentityRevelation(evaluationId);
      if (result.success) {
        toast({ title: 'Solicitud Enviada', description: 'Se notificó al compañero que querés saber su identidad.' });
        setActivities(prev => prev.map(activity => ({
          ...activity,
          peerEvaluations: activity.peerEvaluations.map(ev =>
            ev.id === evaluationId ? { ...ev, identityRequestStatus: 'pending' as const } : ev
          ),
        })));
      } else {
        toast({ variant: 'destructive', description: result.error || 'Error al solicitar identidad.' });
      }
    } catch {
      toast({ variant: 'destructive', description: 'Error de conexión.' });
    }
  };

  useEffect(() => {
    async function fetchActivity() {
      if (!firestore || !playerId) { setIsLoading(false); return; }
      setIsLoading(true);
      try {
        // 1. Fetch evaluations via Secure Server Action
        const { evaluations: allEvals, error: fetchError } = await getPlayerEvaluationsAction(playerId, user?.uid);

        if (fetchError) throw new Error(fetchError);

        if (allEvals.length === 0) { setActivities([]); setIsLoading(false); return; }

        // 2. Group evaluations by matchId
        const evalsByMatchId = allEvals.reduce((acc, ev) => {
          if (!acc[ev.matchId]) acc[ev.matchId] = [];
          acc[ev.matchId].push(ev);
          return acc;
        }, {} as Record<string, Evaluation[]>);

        const matchIds = Object.keys(evalsByMatchId);

        // 3. Fetch matches, ovrHistory, and selfEvaluations in parallel
        const matchPromises = matchIds.map(id => getDoc(doc(firestore, 'matches', id)));

        const ovrHistoryQuery = query(
          collection(firestore, 'players', playerId, 'ovrHistory'),
          where('matchId', 'in', matchIds.slice(0, 10)),
        );

        // selfEvaluations: for each matchId, query the subcollection
        const selfEvalPromises = matchIds.map(matchId =>
          getDocs(query(
            collection(firestore, 'matches', matchId, 'selfEvaluations'),
            where('playerId', '==', playerId),
            limit(1),
          ))
        );

        const [matchSnaps, ovrHistorySnap, ...selfEvalSnaps] = await Promise.all([
          Promise.all(matchPromises),
          matchIds.length > 0 ? getDocs(ovrHistoryQuery) : Promise.resolve({ docs: [] } as any),
          ...selfEvalPromises,
        ]);

        const matchesMap = new Map(
          matchSnaps.map(snap => [snap.id, { id: snap.id, ...snap.data() } as Match])
        );

        const ovrHistoryMap = new Map<string, OvrHistory>();
        ovrHistorySnap.docs.forEach((d: any) => {
          const data = d.data();
          ovrHistoryMap.set(data.matchId, data);
        });

        // Map matchId → selfEvaluation
        const selfEvalMap = new Map<string, SelfEvaluation>();
        matchIds.forEach((matchId, idx) => {
          const snap = selfEvalSnaps[idx];
          if (snap && snap.docs.length > 0) {
            const d = snap.docs[0];
            selfEvalMap.set(matchId, { id: d.id, ...d.data() } as SelfEvaluation);
          }
        });

        const contexts: MatchFeedbackContext[] = [];

        for (const matchId of matchIds) {
          const match = matchesMap.get(matchId);
          if (!match) continue;

          const evals = evalsByMatchId[matchId];
          const peerEvaluations = evals.filter((e: any) => e.evaluatorId !== playerId);

          // Use selfEvaluations subcollection for accurate goals/assists
          const selfEval = selfEvalMap.get(matchId);

          const stats = computeStats(peerEvaluations, selfEval);
          const attributeDeltas = buildAttributeDeltas(peerEvaluations);

          const ovrEntry = ovrHistoryMap.get(matchId);

          // Attach chronicle from selfEvaluation subcollection if available
          const selfEvalWithChronicle = selfEval
            ? { ...selfEval, personalChronicle: selfEval.personalChronicle }
            : undefined;

          contexts.push({
            match,
            selfEvaluation: selfEvalWithChronicle,
            peerEvaluations,
            stats,
            ovrUpdate: ovrEntry
              ? { change: ovrEntry.change, newOVR: ovrEntry.newOVR, oldOVR: ovrEntry.oldOVR }
              : undefined,
            attributeDeltas,
          });
        }

        // Sort by match date descending
        contexts.sort((a, b) => {
          const toMs = (d: any) =>
            d?.toDate ? d.toDate().getTime() : (d ? new Date(d).getTime() : 0);
          return toMs(b.match.date || 0) - toMs(a.match.date || 0);
        });

        setActivities(contexts);
      } catch (error: any) {
        logger.error('Failed to fetch player match debrief', error, { playerId });
      } finally {
        setIsLoading(false);
      }
    }
    fetchActivity();
  }, [firestore, playerId]);

  // ── Hero Stats ────────────────────────────────────────────────────────────────
  const heroStats = useMemo(() => {
    const withRating = activities.filter(a => a.stats.avgRating > 0);
    return {
      totalGoals: activities.reduce((s, a) => s + a.stats.goals, 0),
      avgRating: withRating.length > 0
        ? withRating.reduce((s, a) => s + a.stats.avgRating, 0) / withRating.length
        : 0,
      totalOvrChange: activities.reduce((s, a) => s + (a.ovrUpdate?.change ?? 0), 0),
      matchCount: activities.length,
    };
  }, [activities]);

  // ── Compact mode ──────────────────────────────────────────────────────────────
  if (compact) {
    if (isLoading) return <CompactSkeleton />;
    if (activities.length === 0) return null;

    const [latestMatch] = activities;
    return (
      <div className="space-y-4">
        {/* Hero stats */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 px-1">
          <HeroStat label="Rating Promedio" value={heroStats.avgRating > 0 ? heroStats.avgRating.toFixed(1) : '─'} icon={Star} />
          <HeroStat label="Goles Totales" value={heroStats.totalGoals} icon={Goal} />
          <HeroStat label="Partidos" value={heroStats.matchCount} icon={Calendar} />
          {heroStats.totalOvrChange !== 0 && (
            <div className="flex flex-col gap-0.5">
              <span className="text-[10px] uppercase tracking-widest text-muted-foreground font-medium flex items-center gap-1">
                {heroStats.totalOvrChange > 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
                Tendencia OVR
              </span>
              <span className={cn(
                'text-2xl font-black font-mono tabular-nums leading-none',
                heroStats.totalOvrChange > 0 ? 'text-emerald-600 dark:text-emerald-400' : 'text-red-500',
              )}>
                {heroStats.totalOvrChange > 0 ? '+' : ''}{heroStats.totalOvrChange.toFixed(1)}
              </span>
            </div>
          )}
        </div>

        {/* Último partido */}
        <MatchCard
          ctx={latestMatch}
          playerId={playerId}
          isFirst
          onRequestIdentity={handleRequestIdentity}
          isOwner={isOwner}
        />

        {/* Link al historial completo */}
        <Link
          href={`/players/${playerId}/historial`}
          className="flex items-center justify-center gap-1 text-sm text-primary hover:underline"
        >
          Ver historial completo <ChevronRight className="h-3.5 w-3.5" />
        </Link>
      </div>
    );
  }

  // ── Loading / Empty ───────────────────────────────────────────────────────────
  if (isLoading) {
    return (
      <div className="flex items-center justify-center p-12">
        <Loader2 className="h-7 w-7 animate-spin text-muted-foreground" />
      </div>
    );
  }

  if (activities.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center py-16 text-center space-y-3 text-muted-foreground">
        <Calendar className="h-10 w-10 opacity-30" />
        <p className="text-sm">Aún no hay partidos evaluados.</p>
      </div>
    );
  }

  const [latestMatch, ...previousMatches] = activities;

  return (
    <div className="space-y-6">
      {/* ── Hero Stats Row ──────────────────────────────────────────────────── */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 px-1">
        <HeroStat label="Rating Promedio" value={heroStats.avgRating > 0 ? heroStats.avgRating.toFixed(1) : '─'} icon={Star} />
        <HeroStat label="Goles Totales" value={heroStats.totalGoals} icon={Goal} />
        <HeroStat label="Partidos" value={heroStats.matchCount} icon={Calendar} />
        {heroStats.totalOvrChange !== 0 && (
          <div className="flex flex-col gap-0.5">
            <span className="text-[10px] uppercase tracking-widest text-muted-foreground font-medium flex items-center gap-1">
              {heroStats.totalOvrChange > 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
              Tendencia OVR
            </span>
            <span className={cn(
              'text-2xl font-black font-mono tabular-nums leading-none',
              heroStats.totalOvrChange > 0 ? 'text-emerald-600 dark:text-emerald-400' : 'text-red-500',
            )}>
              {heroStats.totalOvrChange > 0 ? '+' : ''}{heroStats.totalOvrChange.toFixed(1)}
            </span>
          </div>
        )}
      </div>

      {/* ── Latest Match ────────────────────────────────────────────────────── */}
      <MatchCard
        ctx={latestMatch}
        playerId={playerId}
        isFirst
        onRequestIdentity={handleRequestIdentity}
        isOwner={isOwner}
      />

      {/* ── Previous Matches ─────────────────────────────────────────────────── */}
      {previousMatches.length > 0 && (
        <div className="space-y-2">
          <h3 className="text-sm font-semibold text-muted-foreground uppercase tracking-wider px-1">
            Partidos Anteriores
          </h3>
          <div className="space-y-2">
            {previousMatches.map(ctx => (
              <MatchCard
                key={ctx.match.id}
                ctx={ctx}
                playerId={playerId}
                isFirst={false}
                onRequestIdentity={handleRequestIdentity}
                isOwner={isOwner}
              />
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
