type MatchFeedbackContext = {
  match: Match;
  selfEvaluation?: SelfEvaluation;
  peerEvaluations: Evaluation[];
  stats: {
    goals: number;
    assists: number;
    avgRating: number;
  };
  ovrUpdate?: {
    change: number;
    newOVR: number;
    oldOVR?: number;
  };
  attributeDeltas: Record<string, number>;
};

// ─── Constants ────────────────────────────────────────────────────────────────

const ATTR_LABELS: Record<string, string> = {
  pac: 'RIT', sho: 'TIR', pas: 'PAS', dri: 'REG', def: 'DEF', phy: 'FIS',
};

const ATTR_ORDER = ['pac', 'sho', 'pas', 'dri', 'def', 'phy'] as const;

// ─── Helpers ──────────────────────────────────────────────────────────────────

function parseMatchDate(match: Match, selfEval?: SelfEvaluation, peerEvals?: Evaluation[]): Date | null {
  const rawDate = match.date || selfEval?.reportedAt || peerEvals?.[0]?.evaluatedAt;
  if (!rawDate) return null;
  if (typeof (rawDate as any).toDate === 'function') return (rawDate as any).toDate();
  const d = new Date(rawDate as string);
  return isNaN(d.getTime()) ? null : d;
}

function getMatchTitle(match: Match): string {
  if (match.title) return match.title;
  if (match.teams && match.teams.length >= 2) return `${match.teams[0].name} vs ${match.teams[1].name}`;
  return 'Partido Amistoso';
}

function TagIcon({ tag }: { tag: string }) {
  const lower = tag.toLowerCase();
  if (lower.includes('tact')) return <Brain className="h-3.5 w-3.5" />;
  if (lower.includes('veloc')) return <Zap className="h-3.5 w-3.5" />;
  if (lower.includes('gol')) return <Target className="h-3.5 w-3.5" />;
  return <Star className="h-3.5 w-3.5" />;
}

function getEvalType(ev: Evaluation): 'points' | 'tags' | 'text' | 'auto' {
  if (ev.autoGenerated) return 'auto';
  if (ev.rating !== undefined) return 'points';
  if (ev.performanceTags?.length) return 'tags';
  if (ev.textDescription) return 'text';
  return 'auto';
}

function buildAttributeDeltas(peerEvaluations: Evaluation[]): Record<string, number> {
  return peerEvaluations.reduce((acc, ev) => {
    for (const change of (ev.aiAttributeChanges ?? [])) {
      acc[change.attribute] = (acc[change.attribute] ?? 0) + change.change;
    }
    for (const tag of (ev.performanceTags ?? [])) {
      for (const effect of (tag.effects ?? [])) {
        acc[effect.attribute] = (acc[effect.attribute] ?? 0) + effect.change;
      }
    }
    return acc;
  }, {} as Record<string, number>);
}

function computeStats(
  peerEvaluations: Evaluation[],
  selfEval?: SelfEvaluation,
): { goals: number; assists: number; avgRating: number } {
  const ratingEvals = peerEvaluations.filter(e => e.rating !== undefined);
  return {
    goals: selfEval?.goals ?? 0,
    assists: selfEval?.assists ?? 0,
    avgRating: ratingEvals.length > 0
      ? ratingEvals.reduce((sum, e) => sum + e.rating!, 0) / ratingEvals.length
      : 0,
  };
}

