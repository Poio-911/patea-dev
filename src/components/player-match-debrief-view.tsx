function HeroStat({ label, value, icon: Icon }: { label: string; value: string | number; icon?: React.ElementType }) {
  return (
    <div className="flex flex-col gap-0.5">
      <span className="text-[10px] uppercase tracking-widest text-muted-foreground font-medium flex items-center gap-1">
        {Icon && <Icon className="h-3 w-3" />}
        {label}
      </span>
      <span className="text-2xl font-black font-mono tabular-nums text-foreground leading-none">{value}</span>
    </div>
  );
}

function AttributeTable({ deltas }: { deltas: Record<string, number> }) {
  return (
    <div className="space-y-1.5">
      {ATTR_ORDER.map(attr => {
        const delta = deltas[attr] ?? 0;
        return (
          <div key={attr} className="flex items-center gap-3 py-0.5">
            <span className="text-xs text-muted-foreground w-8 font-mono shrink-0">{ATTR_LABELS[attr]}</span>
            {delta !== 0 ? (
              <>
                <div className="flex-1 h-1 rounded-full bg-muted overflow-hidden">
                  <div
                    className={cn('h-full rounded-full', delta > 0 ? 'bg-emerald-500' : 'bg-red-500')}
                    style={{ width: `${Math.min(Math.abs(delta) * 25, 100)}%` }}
                  />
                </div>
                <span className={cn(
                  'text-xs font-bold w-7 text-right tabular-nums shrink-0',
                  delta > 0 ? 'text-emerald-600 dark:text-emerald-400' : 'text-red-500',
                )}>
                  {delta > 0 ? '+' : ''}{delta}
                </span>
              </>
            ) : (
              <span className="text-xs text-muted-foreground/40 flex-1">─</span>
            )}
          </div>
        );
      })}
    </div>
  );
}

function PeerEvalList({
  peerEvals,
  playerId,
  onRequestIdentity,
  isOwner,
}: {
  peerEvals: Evaluation[];
  playerId: string;
  onRequestIdentity: (id: string) => void;
  isOwner: boolean;
}) {
  if (peerEvals.length === 0) {
    return (
      <div className="flex flex-col items-center justify-center py-5 text-center space-y-1.5 opacity-60">
        <MessageSquare className="h-6 w-6 text-muted-foreground/50" />
        <p className="text-sm text-muted-foreground">Sin feedback de compañeros.</p>
      </div>
    );
  }

  return (
    <div>
      {peerEvals.map((ev, idx) => {
        const evalType = getEvalType(ev);

        // Auto-generated: simplified entry
        if (evalType === 'auto') {
          return (
            <div key={ev.id} className={cn('py-2.5', idx < peerEvals.length - 1 && 'border-b border-border/50')}>
              <p className="text-xs text-muted-foreground/50 italic">Evaluación automática</p>
            </div>
          );
        }

        // Compute per-eval tag effects for display
        const evalTagDeltas = evalType === 'tags'
          ? (ev.performanceTags ?? []).reduce((acc, tag) => {
            for (const effect of (tag.effects ?? [])) {
              acc[effect.attribute] = (acc[effect.attribute] ?? 0) + effect.change;
            }
            return acc;
          }, {} as Record<string, number>)
          : null;

        const typeBadge = evalType === 'points'
          ? <span className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground/60 px-1.5 py-0.5 rounded bg-muted/50">Puntos</span>
          : evalType === 'tags'
            ? <span className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground/60 px-1.5 py-0.5 rounded bg-muted/50">Tags</span>
            : <span className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground/60 px-1.5 py-0.5 rounded bg-muted/50">Texto</span>;

        return (
          <div key={ev.id} className={cn('py-3 flex items-start gap-3', idx < peerEvals.length - 1 && 'border-b border-border/50')}>
            {/* Avatar */}
            <Avatar className="h-9 w-9 shrink-0">
              {ev.identityRevealed && ev.evaluatorPhotoUrl ? (
                <AvatarImage src={ev.evaluatorPhotoUrl} />
              ) : ev.identityRevealed ? (
                <AvatarFallback className="bg-primary/20 text-primary font-bold text-xs">
                  {ev.evaluatorDisplayName?.charAt(0).toUpperCase() ?? '?'}
                </AvatarFallback>
              ) : (
                <AvatarFallback className="bg-muted text-muted-foreground">
                  <Lock className="h-3.5 w-3.5" />
                </AvatarFallback>
              )}
            </Avatar>

            {/* Content */}
            <div className="flex-1 min-w-0 space-y-1.5">
              {/* Name row */}
              <div className="flex items-center justify-between gap-2">
                <span className="text-sm font-medium flex items-center gap-1.5">
                  {ev.identityRevealed ? (
                    <span className="flex items-center gap-1 text-primary">
                      <CheckCircle2 className="h-3.5 w-3.5" />
                      {ev.evaluatorDisplayName || 'Identidad revelada'}
                    </span>
                  ) : (
                    'Anónimo'
                  )}
                  {typeBadge}
                </span>
                <div className="flex items-center gap-2 shrink-0">
                  {evalType === 'points' && typeof ev.rating === 'number' && (
                    <span className={cn(
                      'text-sm font-bold tabular-nums px-2 py-0.5 rounded-full',
                      ev.rating >= 8 ? 'bg-emerald-500/10 text-emerald-600 dark:text-emerald-400' :
                        ev.rating >= 6 ? 'bg-amber-500/10 text-amber-600 dark:text-amber-400' :
                          'bg-slate-500/10 text-slate-500',
                    )}>
                      {ev.rating.toFixed(1)}
                    </span>
                  )}
                  {isOwner && !ev.identityRevealed && ev.evaluatorId !== 'AI' && (
                    ev.identityRequestStatus === 'pending' ? (
                      <span className="text-[10px] text-muted-foreground flex items-center gap-1">
                        <Clock className="h-3 w-3" /> Enviada
                      </span>
                    ) : ev.identityRequestStatus === 'rejected' ? (
                      <span className="text-[10px] text-muted-foreground/60 italic">Rechazada</span>
                    ) : (
                      <button
                        onClick={() => onRequestIdentity(ev.id)}
                        className="text-[10px] font-semibold text-primary/80 hover:text-primary hover:underline flex items-center gap-1 transition-colors bg-primary/5 px-2 py-0.5 rounded-full"
                      >
                        <Lock className="h-3 w-3" /> Solicitar ID
                      </button>
                    )
                  )}
                </div>
              </div>

              {/* Tags */}
              {evalType === 'tags' && ev.performanceTags && ev.performanceTags.length > 0 && (
                <>
                  <div className="flex flex-wrap gap-1.5">
                    {ev.performanceTags.map((tag, i) => {
                      const tagName = typeof tag === 'string' ? tag : tag.name;
                      return (
                        <Badge key={i} variant="secondary" className="text-[11px] gap-1 px-2 py-0.5">
                          <TagIcon tag={tagName} />
                          {tagName}
                        </Badge>
                      );
                    })}
                  </div>
                  {evalTagDeltas && Object.values(evalTagDeltas).some(v => v !== 0) && (
                    <div className="flex flex-wrap gap-x-2 gap-y-0.5 mt-0.5">
                      {ATTR_ORDER.filter(a => (evalTagDeltas[a] ?? 0) !== 0).map(attr => (
                        <span key={attr} className={cn(
                          'text-[10px] font-mono font-semibold tabular-nums',
                          evalTagDeltas[attr] > 0 ? 'text-emerald-600 dark:text-emerald-400' : 'text-red-500',
                        )}>
                          {ATTR_LABELS[attr]} {evalTagDeltas[attr] > 0 ? '+' : ''}{evalTagDeltas[attr]}
                        </span>
                      ))}
                    </div>
                  )}
                </>
              )}

              {/* Text eval: summary */}
              {evalType === 'text' && (ev.aiSummary || ev.textDescription) && (
                <p className="text-xs text-muted-foreground italic border-l-2 border-primary/20 pl-2">
                  "{ev.aiSummary ?? ev.textDescription!.slice(0, 120)}"
                </p>
              )}
            </div>
          </div>
        );
      })}
    </div>
  );
}

function MatchCard({
  ctx,
  playerId,
  isFirst,
  onRequestIdentity,
  isOwner,
}: {
  ctx: MatchFeedbackContext;
  playerId: string;
  isFirst: boolean;
  onRequestIdentity: (id: string) => void;
  isOwner: boolean;
}) {
  const matchDate = parseMatchDate(ctx.match, ctx.selfEvaluation, ctx.peerEvaluations);
  const formattedDate = matchDate
    ? format(matchDate, "EEE d MMM yyyy", { locale: es })
    : 'Fecha desconocida';
  const displayTitle = getMatchTitle(ctx.match);
  const hasActiveDeltas = Object.values(ctx.attributeDeltas).some(v => v !== 0);

  const body = (
    <div className="space-y-4">
      {/* Stats row */}
      <div className="flex flex-wrap gap-2 text-sm">
        {ctx.ovrUpdate && (
          <span className={cn(
            'flex items-center gap-1 font-bold tabular-nums px-2.5 py-1 rounded-full text-xs',
            ctx.ovrUpdate.change >= 0
              ? 'bg-emerald-500/10 text-emerald-600 dark:text-emerald-400'
              : 'bg-red-500/10 text-red-500',
          )}>
            {ctx.ovrUpdate.change >= 0 ? <TrendingUp className="h-3.5 w-3.5" /> : <TrendingDown className="h-3.5 w-3.5" />}
            {ctx.ovrUpdate.change >= 0 ? '+' : ''}{ctx.ovrUpdate.change.toFixed(1)} OVR
          </span>
        )}
        {ctx.stats.avgRating > 0 && (
          <span className="flex items-center gap-1 px-2.5 py-1 rounded-full text-xs bg-muted/60 font-medium">
            <Star className="h-3.5 w-3.5 text-amber-500" />
            {ctx.stats.avgRating.toFixed(1)}
          </span>
        )}
        <span className="flex items-center gap-1 px-2.5 py-1 rounded-full text-xs bg-muted/60 font-medium">
          <Goal className="h-3.5 w-3.5 text-primary" />
          {ctx.stats.goals} {ctx.stats.goals === 1 ? 'gol' : 'goles'}
        </span>
        {ctx.stats.assists > 0 && (
          <span className="flex items-center gap-1 px-2.5 py-1 rounded-full text-xs bg-muted/60 font-medium">
            <Target className="h-3.5 w-3.5 text-primary" />
            {ctx.stats.assists} {ctx.stats.assists === 1 ? 'asist.' : 'asist.'}
          </span>
        )}
      </div>

      {/* Attributes table */}
      {hasActiveDeltas && (
        <>
          <Separator />
          <div>
            <p className="text-[10px] uppercase tracking-widest text-muted-foreground mb-2 font-semibold">Atributos</p>
            <AttributeTable deltas={ctx.attributeDeltas} />
          </div>
        </>
      )}

      {/* Chronicle */}
      {ctx.selfEvaluation?.personalChronicle && (
        <>
          <Separator />
          <blockquote className="border-l-2 border-primary/30 pl-3 italic text-sm text-muted-foreground">
            <Quote className="h-3.5 w-3.5 inline-block mr-1 opacity-50 -mt-1" />
            {ctx.selfEvaluation.personalChronicle}
          </blockquote>
        </>
      )}

      {/* Peer evaluations */}
      {(ctx.peerEvaluations.length > 0 || isFirst) && (
        <>
          <Separator />
          <div>
            <p className="text-[10px] uppercase tracking-widest text-muted-foreground mb-1 font-semibold flex items-center gap-1.5">
              <MessageSquare className="h-3 w-3" /> Votos del Vestuario
            </p>
            <PeerEvalList
              peerEvals={ctx.peerEvaluations}
              playerId={playerId}
              onRequestIdentity={onRequestIdentity}
              isOwner={isOwner}
            />
          </div>
        </>
      )}
    </div>
  );

  if (isFirst) {
    return (
      <Card>
        <CardHeader className="pb-3">
          <div className="flex items-start justify-between gap-2">
            <div className="min-w-0">
              <CardTitle className="text-base leading-snug">{displayTitle}</CardTitle>
              <p className="text-xs text-muted-foreground mt-0.5 capitalize">{formattedDate}</p>
            </div>
            <Badge variant="outline" className="text-xs shrink-0">Último</Badge>
          </div>
        </CardHeader>
        <CardContent>{body}</CardContent>
      </Card>
    );
  }

  return (
    <Collapsible className="group">
      <div className="overflow-hidden rounded-xl border bg-card shadow-sm">
        <CollapsibleTrigger className="w-full text-left">
          <div className="px-4 py-3 flex items-center gap-3 bg-muted/30 hover:bg-muted/50 transition-colors">
            <span className="text-xs text-muted-foreground capitalize hidden sm:block w-32 shrink-0">
              {formattedDate}
            </span>
            <span className="text-xs text-muted-foreground capitalize sm:hidden shrink-0">
              {matchDate ? format(matchDate, 'd MMM', { locale: es }) : '—'}
            </span>
            <span className="font-semibold flex-1 truncate text-sm">{displayTitle}</span>
            {ctx.ovrUpdate && (
              <span className={cn(
                'font-bold tabular-nums text-xs shrink-0',
                ctx.ovrUpdate.change >= 0 ? 'text-emerald-600 dark:text-emerald-400' : 'text-red-500',
              )}>
                {ctx.ovrUpdate.change >= 0 ? '+' : ''}{ctx.ovrUpdate.change.toFixed(1)}
              </span>
            )}
            {ctx.stats.avgRating > 0 && (
              <span className="text-xs font-bold tabular-nums shrink-0">{ctx.stats.avgRating.toFixed(1)}</span>
            )}
            <ChevronDown className="h-4 w-4 text-muted-foreground shrink-0 transition-transform group-data-[state=open]:rotate-180" />
          </div>
        </CollapsibleTrigger>
        <CollapsibleContent>
          <div className="px-4 pb-4 pt-3 border-t border-border/40">
            {body}
          </div>
        </CollapsibleContent>
      </div>
    </Collapsible>
  );
}

