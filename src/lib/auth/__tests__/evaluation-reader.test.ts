import { describe, expect, it, vi } from 'vitest';
import { resolveEvaluationReader } from '../evaluation-reader';
import { maskEvaluation } from '../../evaluation-privacy';

describe('identidad del lector de evaluaciones', () => {
  it('usa el token vigente aunque la cookie de otra cuenta esté vencida', async () => {
    const verifyIdToken = vi.fn().mockResolvedValue({ uid: 'token-owner' });
    const requireSession = vi.fn().mockRejectedValue(new Error('expired'));
    expect(await resolveEvaluationReader('valid-token', { verifyIdToken, requireSession })).toBe('token-owner');
    expect(verifyIdToken).toHaveBeenCalledWith('valid-token', true);
    expect(requireSession).not.toHaveBeenCalled();
  });

  it('no cae a la cookie si el token está revocado', async () => {
    const verifyIdToken = vi.fn().mockRejectedValue(new Error('revoked'));
    const requireSession = vi.fn().mockResolvedValue('another-user');
    await expect(resolveEvaluationReader('revoked-token', { verifyIdToken, requireSession })).rejects.toThrow('revoked');
    expect(requireSession).not.toHaveBeenCalled();
  });

  it('mantiene sesión verificada como fallback para callers existentes', async () => {
    const verifyIdToken = vi.fn();
    const requireSession = vi.fn().mockResolvedValue('cookie-owner');
    expect(await resolveEvaluationReader(undefined, { verifyIdToken, requireSession })).toBe('cookie-owner');
    expect(verifyIdToken).not.toHaveBeenCalled();
  });

  it('rechaza credenciales vacías sin consultar una cookie ajena', async () => {
    const verifyIdToken = vi.fn();
    const requireSession = vi.fn();
    await expect(resolveEvaluationReader('', { verifyIdToken, requireSession })).rejects.toThrow();
    expect(requireSession).not.toHaveBeenCalled();
  });
});

describe('privacidad del historial', () => {
  it.each([false, true])('oculta autor y enlaces de evaluación automática=%s', autoGenerated => {
    const evaluation = { id: 'evaluation', evaluatorId: 'author', evaluatorDisplayName: 'Autor',
      evaluatorPhotoUrl: 'photo', evaluatorPhotoURL: 'legacy-photo', evaluatorName: 'Legacy name',
      assignmentId: 'assignment-author', autoGenerated, rating: 7 };
    const result = maskEvaluation(evaluation, 'reader');
    expect(result.evaluatorId).toBe(autoGenerated ? 'AI' : 'anonymous');
    for (const key of ['assignmentId', 'evaluatorDisplayName', 'evaluatorPhotoUrl', 'evaluatorPhotoURL', 'evaluatorName']) {
      expect(result).not.toHaveProperty(key);
    }
    expect(result.rating).toBe(7);
    expect(evaluation.evaluatorId).toBe('author');
  });
  it('conserva la identidad propia o revelada explícitamente', () => {
    const own = { evaluatorId: 'reader', assignmentId: 'own', rating: 8 };
    expect(maskEvaluation(own, 'reader')).toBe(own);
    const revealed = { evaluatorId: 'author', identityRevealed: true };
    expect(maskEvaluation(revealed, 'reader')).toBe(revealed);
  });
});
