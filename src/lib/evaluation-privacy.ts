/** Nunca devolver claves que permitan unir una evaluación anónima a su autor. */
export function maskEvaluation(ev: any, requesterId: string): any {
  if (ev.identityRevealed === true || ev.evaluatorId === requesterId) return ev;
  const { evaluatorId, evaluatorDisplayName, evaluatorPhotoUrl, evaluatorPhotoURL, evaluatorName, assignmentId, ...rest } = ev;
  if (ev.autoGenerated || evaluatorId === 'AI') return { ...rest, evaluatorId: 'AI' };
  return { ...rest, evaluatorId: 'anonymous', isAnonymous: true };
}
