const { test } = require('node:test');
const assert = require('node:assert/strict');
const { buildMatchDateTime } = require('../lib/lib/match-date');
const { maskEvaluation } = require('../lib/lib/evaluation-privacy');

test('recordatorios aceptan el mismo día enviado por web o Flutter, a UTC-3', () => {
  for (const date of ['2026-11-15', '2026-11-15T00:00:00.000', '2026-11-15T00:00:00.000Z']) {
    assert.equal(buildMatchDateTime(date, '22:30').toISOString(), '2026-11-16T01:30:00.000Z');
  }
});

test('recordatorios rechazan fechas imposibles y horarios inválidos', () => {
  for (const [day, time] of [['2026-02-30', '10:00'], ['2026-13-01', '10:00'], ['2026-11-15', '24:00'], ['', '10:00'], ['2026-11-15', '10:60']]) {
    assert.equal(buildMatchDateTime(day, time), null);
  }
  assert.equal(buildMatchDateTime('2028-02-29', '10:00').toISOString(), '2028-02-29T13:00:00.000Z');
});

test('el perfil no permite reconstruir autoría con assignmentId o datos del evaluador', () => {
  const raw = { id: 'evaluation', evaluatorId: 'alice', evaluatorDisplayName: 'Alice', evaluatorPhotoUrl: '/alice', assignmentId: 'alice-bob', playerId: 'bob', rating: 7 };
  const anonymous = maskEvaluation(raw, 'bob');
  assert.equal(anonymous.evaluatorId, 'anonymous');
  for (const field of ['evaluatorDisplayName', 'evaluatorPhotoUrl', 'assignmentId']) assert.equal(field in anonymous, false);
  assert.equal(anonymous.rating, 7);
  assert.equal(maskEvaluation(raw, 'alice'), raw);
  assert.equal(maskEvaluation({ ...raw, identityRevealed: true }, 'bob').evaluatorId, 'alice');
  const automatic = maskEvaluation({ ...raw, autoGenerated: true }, 'bob');
  assert.equal(automatic.evaluatorId, 'AI');
  assert.equal('assignmentId' in automatic, false);
});
