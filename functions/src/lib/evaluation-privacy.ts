/**
 * Quita claves que permiten identificar al autor de la evaluación mientras sea
 * anónima — incluyendo rutas de audio y transcripciones literales de notas de
 * voz, ya que la voz o muletillas delatan al evaluador.
 */
export function maskEvaluation(ev: Record<string, any>, requesterId: string): Record<string, any> {
  const hasAudio = typeof ev.audioPath === 'string' && ev.audioPath.trim().length > 0;
  if (ev.identityRevealed === true || ev.evaluatorId === requesterId) {
    if (!hasAudio && !('audioPath' in ev)) return ev;
    const { audioPath, ...safe } = ev;
    return hasAudio ? { ...safe, hasAudio: true } : safe;
  }
  const {
    evaluatorId,
    evaluatorDisplayName,
    evaluatorName,
    evaluatorPhotoUrl,
    evaluatorPhotoURL,
    assignmentId,
    audioPath,
    audioUrl,
    ...rest
  } = ev;
  if (hasAudio) {
    // Oculta la transcripción literal mientras sea anónima; queda `aiSummary`.
    delete rest.textDescription;
    rest.hasAudio = true;
  }
  if (ev.autoGenerated || evaluatorId === 'AI') {
    return { ...rest, evaluatorId: 'AI' };
  }
  return { ...rest, evaluatorId: 'anonymous', isAnonymous: true };
}
