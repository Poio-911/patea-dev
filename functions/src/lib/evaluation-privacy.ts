/** Quita también claves que permiten unir la evaluación con su asignación. */
export function maskEvaluation(ev: Record<string, any>, requesterId: string): Record<string, any> {
  if (ev.identityRevealed === true || ev.evaluatorId === requesterId) return ev;
  const { evaluatorId, evaluatorDisplayName, evaluatorName, evaluatorPhotoUrl, evaluatorPhotoURL, assignmentId, ...rest } = ev;
  if (ev.autoGenerated || evaluatorId === 'AI') {
    return { ...rest, evaluatorId: 'AI' };
  }
  return { ...rest, evaluatorId: 'anonymous', isAnonymous: true };
}
